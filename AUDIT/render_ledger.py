#!/usr/bin/env python3
"""Render AUDIT/ledger.md from the canonical AUDIT/ledger.json.

The ledger is the source of truth; this view is regenerated, never hand-edited.
Usage: python3 AUDIT/render_ledger.py
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "AUDIT" / "ledger.json"
VIEW = ROOT / "AUDIT" / "ledger.md"

LEGEND = (
    "START = statically demonstrated condition; OPEN = investigation/gate, not a "
    "confirmed defect; BLOCKED = an environment/owner blocker; IN_PROGRESS = a fix "
    "is being implemented; DONE = fixed and verified with evidence and a commit. "
    "Severity on candidates is provisional."
)


def counts(tasks: list[dict]) -> str:
    c = Counter(t["status"] for t in tasks)
    parts = [
        f"done:{c.get('DONE', 0)}",
        f"in_progress:{c.get('IN_PROGRESS', 0)}",
        f"open:{c.get('OPEN', 0)}",
        f"start:{c.get('START', 0)}",
        f"blocked:{c.get('BLOCKED', 0)}",
    ]
    return " ".join(parts)


def main() -> None:
    data = json.loads(LEDGER.read_text(encoding="utf-8"))
    tasks = data["tasks"]
    lines = [
        "# TinyTitan audit ledger",
        "",
        "**Source of truth:** `AUDIT/ledger.json` (this page is generated by "
        "`AUDIT/render_ledger.py`). The task manual is [TASKS.md](TASKS.md).",
        "",
        f"Branch: `{data.get('branch', '')}`. Base revision: "
        f"`{data.get('revision', '')}`. State: `{data.get('state', '')}`.",
        "",
        LEGEND,
        "",
        f"**{counts(tasks)}**",
        "",
        "| ID | Severity | Status | Project | Title |",
        "|---|---|---|---|---|",
    ]
    for t in tasks:
        lines.append(
            f"| {t['id']} | {t['severity']} | {t['status']} | {t['project']} | {t['title']} |"
        )
    lines.append("")
    for t in tasks:
        lines += [
            f"## {t['id']} — {t['title']}",
            "",
            f"- {t['severity']} / Tier {t['tier']} / {t['status']} / {t['category']}",
            f"- Project: {t['project']}; host: {t['host']}",
            f"- Location: {t['file:line']}",
            f"- Evidence before: {t.get('evidence-before') or 'none recorded'}",
        ]
        if t.get("evidence-after"):
            lines.append(f"- Evidence after: {t['evidence-after']}")
        if t.get("fix-summary"):
            lines.append(f"- Fix: {t['fix-summary']}")
        if t.get("commit"):
            lines.append(f"- Commit: `{t['commit']}`")
        if t.get("blocked-reason"):
            lines.append(f"- Blocked: {t['blocked-reason']}")
        lines.append("")
    VIEW.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {VIEW.relative_to(ROOT)} ({len(tasks)} tasks, {counts(tasks)})")


if __name__ == "__main__":
    main()
